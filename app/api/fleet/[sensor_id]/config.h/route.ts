import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'

// Deployment-specific values come from the environment, never from source.
// WIFI_SSID / WIFI_PASSWORD are the network the sensors join; PUBLIC_URL is this deployment's origin.
const esc = (v: string) => v.replace(/[\\"\r\n]/g, '')

export async function GET(req: NextRequest, { params }: { params: Promise<{ sensor_id: string }> }) {
  const { sensor_id } = await params
  const sensor = await prisma.sensors.findUnique({ where: { id: sensor_id } })
  if (!sensor) return NextResponse.json({ error: 'not found' }, { status: 404 })

  const WIFI_SSID = esc(process.env.SENSOR_WIFI_SSID ?? '')
  const WIFI_PASSWORD = esc(process.env.SENSOR_WIFI_PASSWORD ?? '')
  const SERVER_URL = esc(process.env.PUBLIC_URL || req.nextUrl.origin)
  const NAME = esc(sensor.name)
  const content = `#pragma once
// Auto-generated by Billboard Fleet — do not edit manually.

#define WIFI_SSID      "${WIFI_SSID}"
#define WIFI_PASSWORD  "${WIFI_PASSWORD}"

#define SERVER_URL     "${SERVER_URL}"
#define DEVICE_API_KEY "${sensor.api_key}"
#define DEVICE_NAME    "${NAME}"

#define BATCH_MAX      80
#define WIFI_TIMEOUT_S 15
`
  return new Response(content, {
    headers: {
      'Content-Type': 'text/plain',
      'Content-Disposition': 'attachment; filename="config.h"',
    },
  })
}
